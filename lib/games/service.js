// Games: the challenge lifecycle. One player per random historical roster.
//   start     -> a new challenge for a sport + the first random team-season roll
//   pick      -> draft ONE player from the currently rolled roster; the server
//                then rolls a brand-new random team-season for the next pick
//   reroll    -> swap the current roll for a new random team-season. Once per
//                draft; the opening roll and the automatic rolls are free
//   roll      -> retry an automatic roll that failed (ESPN down); never the reroll
//   lock      -> a complete squad is locked for simulation
//   simulate  -> a seeded season on the real schedule of the team-season the
//                first pick came from; the run's summary is stored
//   rebuild   -> after locking: start a fresh draft (new rolls, new reroll).
//                Old runs keep their own squads
// The server holds all draft state (picks, current roll, reroll used), so a
// refresh or another device resumes exactly. Picks and rolls on one challenge
// run one at a time, and each pick/reroll names the roll it was made against,
// so double clicks and stale tabs can't draft twice or roll twice.
// Each pick stores a snapshot of the player as drafted (real stats, PPG,
// career facts), so the squad never depends on re-loading old rosters.

const crypto = require('node:crypto');
const { SPORTS, ORDER, seasonsFor, slotKeys, publicSport } = require('./sports');
const squadLib = require('./squad');
const sim = require('./sim');
const fantasy = require('./fantasy');
const chemistry = require('./chemistry');
const { seasonLabeler } = require('./history');

class GameError extends Error { constructor(code, msg) { super(msg); this.code = code; } }

const ENGINE = 3; // bump when the sim changes in a way that alters replays (3: one pick per random team-season)
const MAX_TRIES = 8;
const DISCLAIMER = 'Simulated seasons are generated by the GMmode simulator. They are not real games and never happened. Rosters, player stats and fantasy points are real, from ESPN box scores of the seasons each player was drafted from; chemistry links come from ESPN athlete records.';
const HOW = 'Draft one player from each randomly generated historical team and season. After every selection, a new team and season are rolled automatically. You get one manual reroll per simulation.';

function createService({ store, history, random = Math.random, now = Date.now }) {
  const db = store.db;
  db.attempts ||= {};

  const get = (id) => {
    const a = db.attempts[String(id || '')];
    if (!a) throw new GameError(404, 'That challenge doesn\'t exist (or it was cleared).');
    return normalize(a);
  };
  const own = (uid, id) => {
    const a = get(id);
    if (a.uid !== uid) throw new GameError(403, 'That\'s someone else\'s challenge. Start your own!');
    return a;
  };
  const sportOf = (key) => { if (!SPORTS[key]) throw new GameError(400, 'Pick a sport.'); return key; };

  // One change at a time per challenge (picks, rolls, rerolls, rebuilds).
  const queues = new Map();
  function serial(id, fn) {
    const prev = queues.get(id) || Promise.resolve();
    const next = prev.catch(() => {}).then(fn);
    const tail = next.catch(() => {});
    queues.set(id, tail);
    tail.then(() => { if (queues.get(id) === tail) queues.delete(id); });
    return next;
  }

  // Challenges from the single-roster version: one team-season, a squad map.
  // Read through a VIEW, never rewritten in place, so opening (or any other
  // save) can't alter an old locked or finished challenge. Its picks all come
  // from that one roster, whose schedule is the schedule. `runs` is the same
  // array, so simulating an old locked squad again still records the run.
  // An old UNFINISHED draft is upgraded once, by its owner opening it (upgrade).
  function normalize(a) {
    if (a.picks) return a;
    const home = { season: a.season, teamId: String(a.teamId), team: a.team, seasonLabel: a.seasonLabel };
    return {
      ...a, legacy: true, _legacy: true, home,
      picks: Object.entries(a.squad || {}).map(([key, playerId], i) => ({ n: i + 1, key, playerId: String(playerId), season: a.season, teamId: String(a.teamId), team: a.team, seasonLabel: a.seasonLabel })),
      roll: null, rolled: [tsKey(a.season, a.teamId)], rerollUsed: true, rollCount: 0,
    };
  }
  // The stored record behind a challenge (what a change must be written to).
  const stored = (a) => db.attempts[a.id];

  function config() {
    return {
      sports: ORDER.map(publicSport), disclaimer: DISCLAIMER, how: HOW,
      scoring: Object.fromEntries(ORDER.map((k) => [k, fantasy.describe(k)])), chemistry: chemistry.describe(),
    };
  }

  // ---------- squad state ----------
  const pickFor = (a, key) => a.picks.find((p) => p.key === key) || null;
  const openSlots = (a) => slotKeys(a.sport).filter((k) => !pickFor(a, k.key));
  const complete = (a) => openSlots(a).length === 0;
  const tsKey = (season, teamId) => `${season}|${teamId}`;

  // A team-season we can draft from: complete data, decent coverage.
  async function loadRoster(sportKey, season, teamId, label) {
    const busy = () => new GameError(503, `Couldn't load the full ${label || 'roster'} from ESPN right now. Try again in a minute.`);
    let ts;
    try { ts = await history.teamSeason(sportKey, season, teamId); } catch { throw busy(); }
    if (ts.partial) throw busy();
    return ts;
  }

  // A brand-new random team-season with at least one player who can fill an
  // open slot. Skips team-seasons already rolled in this draft, incomplete
  // data and thin box scores. Nothing is changed here; the caller commits.
  async function findRoll(a) {
    const seasons = seasonsFor(a.sport);
    const open = openSlots(a);
    const taken = new Set(a.picks.map((p) => String(p.playerId)));
    const seen = new Set(a.rolled);
    let lastErr = null;
    for (let i = 0; i < MAX_TRIES; i++) {
      const season = seasons[Math.floor(random() * seasons.length)];
      try {
        const st = await history.standings(a.sport, season);
        const team = st.teams[Math.floor(random() * st.teams.length)];
        if (!team || seen.has(tsKey(season, team.id))) { lastErr = new Error('already rolled'); continue; }
        const ts = await history.teamSeason(a.sport, season, team.id);
        if (ts.partial) { lastErr = new Error('ESPN fetches failed mid-season'); continue; }
        if (ts.coverage.boxScores < ts.coverage.games * 0.8) { lastErr = new Error('thin box scores'); continue; }
        if (!ts.players.some((p) => !taken.has(String(p.id)) && open.some((o) => squadLib.fits(o.slot, p).length))) { lastErr = new Error('nobody fits an open slot'); continue; }
        return ts;
      } catch (e) { lastErr = e; }
    }
    console.error(`[games] roll ${a.sport} failed: ${lastErr?.message}`);
    throw new GameError(503, 'Couldn\'t pull a historical roster right now. ESPN may be slow, so give it another try.');
  }
  function commitRoll(a, ts) {
    a.rollCount = (a.rollCount || 0) + 1;
    a.roll = { n: a.rollCount, season: ts.season, teamId: String(ts.team.id), team: teamInfo(ts.team), seasonLabel: ts.seasonLabel, at: now() };
    a.rolled.push(tsKey(ts.season, ts.team.id));
    a.rollFailed = false;
  }
  const teamInfo = (t) => ({ name: t.name, abbr: t.abbr, logo: t.logo || null, color: t.color || null });

  // Turn a legacy view into a stored new-format record (same id, same runs).
  function materialize(view) {
    const { _legacy, legacy, squad, season, teamId, team, seasonLabel, ...rest } = view;
    const rec = { ...rest, draft: rest.draft || 1, upgradedFrom: 'single-roster' };
    db.attempts[view.id] = rec;
    return rec;
  }

  // An old single-roster draft that was never finished becomes a normal draft:
  // its picks keep their original players (snapshotted from their original
  // roster), it gets a real random roll for the next pick, and one unused
  // manual reroll. Nothing is written unless the original roster loads, so a
  // failure leaves the old challenge exactly as it was.
  async function upgrade(view) {
    const home = view.home;
    const ts = await loadRoster(view.sport, home.season, home.teamId, `${home.seasonLabel} ${home.team?.name || ''}`.trim());
    const slots = new Map(slotKeys(view.sport).map((k) => [k.key, k.slot]));
    const picks = view.picks.map((p, i) => {
      const pl = ts.players.find((x) => String(x.id) === String(p.playerId));
      const slot = slots.get(p.key);
      if (!pl || !slot) return { ...p, n: i + 1 };
      return {
        ...p, n: i + 1, group: squadLib.fits(slot, pl)[0] || pl.group, at: view.createdAt,
        team: teamInfo(ts.team), L: ts.league.avgFor, league: ts.league.slug, player: snapshot(pl), bio: pl.unit ? null : (ts.chemBios?.[pl.id] || null),
      };
    });
    const rec = materialize({ ...view, picks, roll: null, rollCount: 0, rolled: [tsKey(home.season, home.teamId)], rerollUsed: false, locked: false });
    try { commitRoll(rec, await findRoll(rec)); } catch { /* no roll yet: the next open (or the retry button) rolls again */ }
    store.save();
    return rec;
  }

  // Opening a challenge (the page load). For the owner of an unfinished draft
  // it makes sure there's a team to draft from: an old draft is upgraded once,
  // and a draft whose last automatic roll failed gets one more try. Neither
  // touches the manual reroll. Once a roll exists this changes nothing, so
  // refreshing is free.
  async function open(uid, id) {
    await serial(id, async () => {
      const a = get(id);
      if (a.uid !== uid || a.locked || complete(a) || a.roll) return;
      if (a._legacy) { await upgrade(a); return; }
      try { commitRoll(a, await findRoll(a)); store.save(); } catch { /* still down: the UI offers a retry */ }
    }).catch((e) => { if (!(e instanceof GameError)) throw e; });
    return view(uid, id);
  }

  // ---------- lifecycle ----------
  async function start(uid, sportKey) {
    sportOf(sportKey);
    const a = { id: crypto.randomUUID(), uid, sport: sportKey, createdAt: now(), picks: [], roll: null, rollCount: 0, rolled: [], rerollUsed: false, home: null, locked: false, runs: [], draft: 1 };
    const ts = await findRoll(a); // a failed first roll creates nothing
    commitRoll(a, ts);
    db.attempts[a.id] = a;
    store.save();
    return view(uid, a.id);
  }

  async function pick(uid, id, { playerId, roll, slot } = {}) {
    return serial(id, async () => {
      let a = own(uid, id);
      if (a._legacy && !a.locked && !complete(a)) a = await upgrade(a); // an old unfinished draft: upgrade first
      if (a.locked) throw new GameError(409, 'This squad is locked in. Hit "Rebuild squad" to draft again.');
      if (complete(a)) throw new GameError(409, 'Your squad is already complete.');
      if (!a.roll) throw new GameError(409, 'There\'s no team to draft from yet. Roll the next team.');
      if (Number(roll) !== a.roll.n) throw new GameError(409, 'You already drafted from that team. Here\'s the current one.');
      const ts = await loadRoster(a.sport, a.roll.season, a.roll.teamId, `${a.roll.seasonLabel} ${a.roll.team.name}`);
      const p = ts.players.find((x) => String(x.id) === String(playerId));
      if (!p) throw new GameError(400, `That player wasn't on the ${a.roll.seasonLabel} ${a.roll.team.name} roster.`);
      if (a.picks.some((x) => String(x.playerId) === String(p.id))) throw new GameError(400, `${p.name} is already in your squad.`);
      const open = openSlots(a);
      let target;
      if (slot) {
        target = open.find((o) => o.key === slot);
        if (!target) throw new GameError(400, slotKeys(a.sport).some((o) => o.key === slot) ? 'That slot is already filled.' : `There's no ${slot} slot in this challenge.`);
        if (!squadLib.fits(target.slot, p).length) throw new GameError(400, `${p.name} (${p.pos}) can't fill a ${target.slot.label} slot.`);
      } else {
        const fitting = open.filter((o) => squadLib.fits(o.slot, p).length);
        target = fitting.find((o) => !o.slot.flex) || fitting[0];
        if (!target) throw new GameError(400, `Every slot ${p.name} can play is already filled.`);
      }
      const group = squadLib.fits(target.slot, p)[0];
      a.picks.push({
        n: a.picks.length + 1, key: target.key, playerId: String(p.id), group, at: now(),
        season: ts.season, teamId: String(ts.team.id), team: teamInfo(ts.team), seasonLabel: ts.seasonLabel, L: ts.league.avgFor, league: ts.league.slug,
        player: snapshot(p), bio: p.unit ? null : (ts.chemBios?.[p.id] || null),
      });
      if (!a.home) a.home = { season: ts.season, teamId: String(ts.team.id), team: teamInfo(ts.team), seasonLabel: ts.seasonLabel };
      a.roll = null; // this roster is used up
      store.save();
      if (!complete(a)) {
        try { commitRoll(a, await findRoll(a)); } catch { a.rollFailed = true; } // the pick stands; the roll can be retried
        store.save();
      }
      return view(uid, id);
    });
  }

  // Retry an automatic roll that failed. Doesn't touch the manual reroll.
  async function nextRoll(uid, id) {
    return serial(id, async () => {
      let a = own(uid, id);
      if (a._legacy && !a.locked && !complete(a)) a = await upgrade(a); // an old unfinished draft: upgrade first
      if (a.locked || complete(a)) throw new GameError(409, 'The draft is over.');
      if (a.roll) return view(uid, id);
      commitRoll(a, await findRoll(a));
      store.save();
      return view(uid, id);
    });
  }

  async function reroll(uid, id, { roll } = {}) {
    return serial(id, async () => {
      let a = own(uid, id);
      if (a._legacy && !a.locked && !complete(a)) a = await upgrade(a); // an old unfinished draft: upgrade first
      if (a.locked || complete(a)) throw new GameError(409, 'The draft is over.');
      if (a.rerollUsed) throw new GameError(409, 'You\'ve already used your one reroll for this draft.');
      if (!a.roll || Number(roll) !== a.roll.n) throw new GameError(409, 'That team has already changed. Here\'s the current one.');
      const ts = await findRoll(a); // fails -> nothing changes, the reroll is kept
      commitRoll(a, ts);
      a.rerollUsed = true;
      store.save();
      return view(uid, id);
    });
  }

  async function lock(uid, id) {
    return serial(id, async () => {
      const a = own(uid, id);
      if (a.locked) return view(uid, id);
      if (!complete(a)) throw new GameError(400, `Still to fill: ${squadLib.describeMissing(a.sport, openSlots(a).map((o) => o.key))}.`);
      a.locked = true;
      if (a._legacy) stored(a).locked = true; // an old finished draft stays in its old format
      store.save();
      return view(uid, id);
    });
  }

  // A fresh draft for this challenge: new rolls, new reroll. Old runs keep their squads.
  async function rebuild(uid, id) {
    return serial(id, async () => {
      const a = own(uid, id);
      if (!a.locked) throw new GameError(409, 'Finish and lock your draft first.');
      const fresh = { sport: a.sport, picks: [], rolled: [] };
      const ts = await findRoll(fresh); // fails -> the old squad stays as it was
      const rec = a._legacy ? materialize(a) : a; // rebuilding an old challenge makes it a new-format draft (same id, same runs)
      Object.assign(rec, { picks: [], home: null, roll: null, rolled: [], rerollUsed: false, locked: false, draft: (a.draft || 1) + 1 });
      commitRoll(rec, ts);
      store.save();
      return view(uid, id);
    });
  }

  // ---------- squad -> sim input ----------
  async function homeSeason(a, home = a.home) {
    if (!home) return null;
    return loadRoster(a.sport, home.season, home.teamId, `${home.seasonLabel} ${home.team.name} schedule`);
  }
  // Picks -> [{ key, slot, player, group, ppg, L, from }] in slot order.
  async function resolvePicks(a, picks) {
    // Legacy picks have no snapshot: read them from their one roster.
    let legacyTs = null;
    if (picks.some((p) => !p.player)) legacyTs = await homeSeason(a, { season: picks[0].season, teamId: picks[0].teamId, team: picks[0].team, seasonLabel: picks[0].seasonLabel });
    return slotKeys(a.sport).map(({ key, slot }) => {
      const p = picks.find((x) => x.key === key);
      if (!p) return { key, slot, player: null, group: null, ppg: null };
      const player = p.player || legacyTs.players.find((x) => String(x.id) === String(p.playerId));
      if (!player) throw new GameError(503, 'A drafted player\'s season couldn\'t be loaded. Try again in a minute.');
      const group = p.group || squadLib.fits(slot, player)[0];
      return { key, slot, player, group, ppg: player.pg[group] ?? player.mppg, L: p.L || legacyTs?.league.avgFor, from: `${p.seasonLabel} ${p.team.abbr || p.team.name}`, pick: p };
    });
  }

  // Chemistry facts for a drafted or candidate player, including the
  // franchise-season he's drafted from (players drafted from different years
  // of one franchise were teammates if their careers overlapped there).
  const bioOf = (x) => (x.bio === null || x.player?.unit ? null : x.bio && {
    college: x.bio.college || null, nat: x.bio.nat || [],
    past: [...(x.bio.past || []), { s: x.season, t: String(x.teamId), lg: x.league }],
  });

  // Verified links among the picks (and between candidates and the picks),
  // with period-correct team names looked up for whatever links are found.
  async function chemistryOf(a, picks, candidates = []) {
    const label = seasonLabeler(a.sport);
    const bios = {}; const all = [...picks.map((p) => ({ id: String(p.playerId), b: bioOf(p) })), ...candidates.map((c) => ({ id: String(c.id), b: c.bio }))];
    for (const x of all) bios[x.id] = x.b;
    const pickIds = picks.map((p) => String(p.playerId));
    const pairsToCheck = [];
    for (let i = 0; i < pickIds.length; i++) for (let j = i + 1; j < pickIds.length; j++) pairsToCheck.push([pickIds[i], pickIds[j]]);
    for (const c of candidates) for (const pid of pickIds) pairsToCheck.push([String(c.id), pid]);
    // First pass without names, to find which names are needed.
    const needTeams = new Map(), needNat = new Set();
    const live = [];
    for (const [x, y] of pairsToCheck) {
      const c = chemistry.pair(bios[x], bios[y]);
      if (!c) continue;
      live.push([x, y]);
      const mine = new Map((bios[x].past || []).map((e) => [`${e.s}|${e.t}`, e]));
      for (const e of bios[y].past || []) if (mine.has(`${e.s}|${e.t}`)) needTeams.set(`${e.s}|${e.t}`, e);
      const nat = new Set((bios[x].nat || []).map((e) => `${e.c}|${e.s}|${e.t}`));
      for (const e of bios[y].nat || []) if (nat.has(`${e.c}|${e.s}|${e.t}`)) needNat.add(e.t);
    }
    let names = { teams: {}, nat: {} };
    if (live.length) { try { names = await history.names(a.sport, { teams: [...needTeams.values()], nat: [...needNat] }); } catch { /* names are cosmetic */ } }
    const pairs = {};
    for (const [x, y] of live) pairs[chemistry.pairKey(x, y)] = chemistry.pair(bios[x], bios[y], names, label);
    return pairs;
  }

  // ---------- views ----------
  function snapshot(p) {
    return {
      id: String(p.id), name: p.name, pos: p.pos, elig: p.elig, group: p.group, gp: p.gp, key: p.key, line: p.line, pkey: p.pkey || null, pline: p.pline || null,
      ppg: p.ppg, mppg: p.mppg, pg: p.pg, rate: p.rate, unit: !!p.unit,
      fp: Object.fromEntries(Object.entries(p.fp).map(([g, x]) => [g, { gp: x.gp, ppg: x.ppg, mppg: x.mppg, parts: (x.parts || []).map((y) => ({ label: y.label, n: Math.round(y.n * 10) / 10, ppg: y.ppg })) }])),
    };
  }
  function publicPlayer(p, ts) {
    const s = snapshot(p);
    delete s.rate;
    return { ...s, college: ts.bios?.[p.id]?.college || null, historyKnown: !!ts.bios?.[p.id]?.known };
  }
  const publicRoster = (ts, players = true) => ({
    season: ts.season, seasonLabel: ts.seasonLabel, team: ts.team, record: ts.record, coverage: ts.coverage, source: ts.source,
    games: ts.schedule.length, history: ts.coverage.history || null,
    ...(players ? { players: ts.players.map((p) => publicPlayer(p, ts)) } : {}),
  });
  function publicPick(p) {
    const pl = p.player || {};
    return {
      n: p.n, key: p.key, playerId: p.playerId, group: p.group, season: p.season, seasonLabel: p.seasonLabel, team: p.team,
      player: { id: p.playerId, name: pl.name, pos: pl.pos, elig: pl.elig, ppg: pl.fp?.[p.group]?.ppg ?? pl.ppg, mppg: pl.pg?.[p.group] ?? pl.mppg, gp: pl.fp?.[p.group]?.gp ?? pl.gp, line: (p.group === 'SP' || p.group === 'RP') && pl.pline ? pl.pline : pl.line, college: p.bio?.college?.name || null, unit: !!pl.unit },
    };
  }
  function publicAttempt(a, uid) {
    const mine = a.uid === uid;
    return {
      id: a.id, sport: a.sport, createdAt: a.createdAt, mine, locked: a.locked, legacy: !!a.legacy, draft: a.draft || 1,
      picks: a.picks.map(publicPick), complete: complete(a), open: openSlots(a).map((o) => o.key), total: slotKeys(a.sport).length,
      roll: mine && a.roll ? { n: a.roll.n, season: a.roll.season, teamId: a.roll.teamId, seasonLabel: a.roll.seasonLabel, team: a.roll.team } : null,
      rollFailed: mine && !a.roll && !complete(a) && !a.locked, rerollUsed: !!a.rerollUsed, rolls: a.rollCount || 0,
      home: a.home, seasonLabel: a.home?.seasonLabel || null, team: a.home?.team || null,
      runs: a.runs.map(({ squad, seed, picks, ...r }) => r),
    };
  }

  // Combined PPG and chemistry for the picks so far, which players on the
  // current roll would bring chemistry, and (once complete) a projection.
  // The percentile and win-model constants stay server-side.
  async function preview(a, rollTs, homeTs) {
    const res = await resolvePicks(a, a.picks);
    const candidates = rollTs ? rollTs.players.filter((p) => !p.unit && !a.picks.some((x) => String(x.playerId) === String(p.id))).map((p) => ({ id: p.id, name: p.name, ppg: p.mppg, bio: bioOf({ bio: rollTs.chemBios?.[p.id] || null, season: rollTs.season, teamId: rollTs.team.id, league: rollTs.league.slug }) })) : [];
    const pairs = await chemistryOf(a, a.picks, candidates.filter((c) => c.bio));
    const ts = { ...(homeTs || rollTs || { league: { avgFor: 1 }, schedule: [] }), pairs };
    const prof = sim.profile(a.sport, ts, res);
    const members = res.filter((s) => s.player).map((s) => ({ id: s.player.id, name: s.player.name, ppg: s.ppg || 0 }));
    const hints = {};
    if (members.length) for (const c of candidates) { const d = chemistry.delta(members, c, pairs); if (d.with.length) hints[c.id] = d; }
    const out = {
      complete: prof.complete, combined: prof.combined, base: prof.base,
      chem: { total: prof.chem.total, players: Object.fromEntries(Object.entries(prof.chem.players).map(([id, x]) => [id, { bonus: x.bonus, links: x.links, capped: !!x.capped }])), links: prof.chem.links.map((l) => ({ a: l.a, b: l.b, aName: l.aName, bName: l.bName, ppg: l.ppg, kinds: l.kinds })) },
      slots: prof.slots, hints, odds: null,
    };
    if (prof.complete && homeTs) {
      const seed = `${a.id}:preview:${a.draft || 1}:${a.picks.map((p) => p.playerId).join(',')}`;
      const o = sim.odds({ sportKey: a.sport, ts, res, runs: 300, seed });
      out.odds = { chance: o.chance, avgWins: o.avgWins, low: o.low, high: o.high, games: o.games, runs: o.runs, objective: o.objective };
      if (prof.chem.total > 0) {
        const w = sim.odds({ sportKey: a.sport, ts, res, runs: 300, seed, chem: false });
        out.odds.chemWins = Math.round((o.avgWins - w.avgWins) * 10) / 10;
      }
    }
    return out;
  }

  async function view(uid, id, { run = null } = {}) {
    const a = get(id);
    const mine = a.uid === uid;
    const out = { attempt: publicAttempt(a, uid), rules: publicSport(a.sport), disclaimer: DISCLAIMER, how: HOW };
    const rollTs = mine && a.roll && !a.locked ? await loadRoster(a.sport, a.roll.season, a.roll.teamId, `${a.roll.seasonLabel} ${a.roll.team.name}`) : null;
    // The schedule only feeds the header and the projection: if ESPN is slow,
    // show the draft without them rather than an error page.
    let homeTs = null;
    if (a.home) { try { homeTs = await homeSeason(a); } catch (e) { if (a.locked || a.runs.length) throw e; } }
    if (rollTs) out.pool = publicRoster(rollTs);
    if (homeTs) out.homeSeason = publicRoster(homeTs, false);
    if (mine || a.runs.length) {
      try { out.preview = await preview(a, rollTs, homeTs); } catch (e) { if (a.locked || a.runs.length) throw e; out.preview = null; } // ESPN slow: the draft shows, the totals come back next load
    }
    const n = run ?? a.runs.length;
    if (n) out.result = await replay(a, n);
    return out;
  }

  // ---------- simulation ----------
  async function simulate(uid, id) {
    return serial(id, async () => {
      const a = own(uid, id);
      if (!a.locked) throw new GameError(409, 'Lock in your squad first.');
      if (a.runs.length >= 50) throw new GameError(429, 'That\'s 50 sims of this squad. Draft a new one!');
      const homeTs = await homeSeason(a);
      const n = a.runs.length + 1, seed = `${a.id}:${n}`;
      const pv = await preview(a, null, homeTs);
      const res = await resolvePicks(a, a.picks);
      const ts = { ...homeTs, pairs: await chemistryOf(a, a.picks) };
      const r = sim.simulateSeason({ sportKey: a.sport, ts, res, seed });
      a.runs.push({
        n, seed, engine: ENGINE, at: now(), picks: a.picks, home: a.home, draft: a.draft || 1,
        record: r.record, played: r.played, success: r.success, perfect: r.perfect, undefeated: r.undefeated,
        combined: r.team.combined, chem: r.team.chem, maxStreak: r.maxStreak, firstBlemish: r.firstBlemish, pf: r.pf, pa: r.pa, tier: r.tier, beatReal: r.beatReal,
        mvp: r.mvp ? { name: r.mvp.name, slot: r.mvp.slotLabel, line: r.mvp.sim } : null, chance: pv.odds?.chance ?? null, chemWins: pv.odds?.chemWins ?? null,
        teams: new Set(a.picks.map((p) => tsKey(p.season, p.teamId))).size,
      });
      store.save();
      return view(uid, id, { run: n });
    });
  }

  async function replay(a, n) {
    const run = a.runs[n - 1];
    if (!run) throw new GameError(404, 'No such run.');
    // Runs from the single-roster version stored a squad map on one roster.
    const picks = run.picks || Object.entries(run.squad || {}).map(([key, playerId]) => ({ key, playerId, season: a.home.season, teamId: a.home.teamId, team: a.home.team, seasonLabel: a.home.seasonLabel }));
    const home = run.home || a.home;
    const homeTs = await homeSeason(a, home);
    const res = await resolvePicks(a, picks);
    const pairs = run.picks ? await chemistryOf(a, picks) : (homeTs.pairs || {});
    const r = sim.simulateSeason({ sportKey: a.sport, ts: { ...homeTs, pairs }, res, seed: run.seed });
    // If the engine changed since this run, the stored summary is what happened.
    const drift = r.record.w !== run.record.w || r.record.l !== run.record.l || r.record.t !== run.record.t || r.record.otl !== run.record.otl;
    return {
      n, of: a.runs.length, at: run.at, chance: run.chance, chemWins: run.chemWins ?? null, drift, engine: run.engine,
      home: { ...home, record: homeTs.record, games: homeTs.schedule.length }, picks: picks.map((p) => (p.player ? publicPick(p) : { key: p.key, playerId: p.playerId, season: p.season, seasonLabel: p.seasonLabel, team: p.team })),
      ...r,
    };
  }

  async function runView(uid, id, n) {
    return view(uid, id, { run: Number(n) });
  }

  // Your challenges, newest first, and your best run per sport.
  function mine(uid) {
    const list = Object.values(db.attempts).filter((a) => a.uid === uid).map(normalize).sort((x, y) => y.createdAt - x.createdAt);
    const score = (r) => (r.success ? 1e6 : 0) + (r.record.w + 0.5 * r.record.t) / r.played * 1e3 + r.maxStreak;
    const best = {};
    const runs = [];
    for (const a of list) {
      for (const r of a.runs) {
        const home = r.home || a.home || {};
        const row = { attemptId: a.id, sport: a.sport, seasonLabel: home.seasonLabel, team: home.team, teams: r.teams ?? 1, n: r.n, at: r.at, record: r.record, played: r.played, success: r.success, perfect: r.perfect, combined: r.combined ?? null, chem: r.chem ?? null, maxStreak: r.maxStreak, tier: r.tier, mvp: r.mvp, chance: r.chance, pf: r.pf, pa: r.pa, beatReal: r.beatReal };
        runs.push(row);
        if (!best[a.sport] || score(r) > score(best[a.sport])) best[a.sport] = row;
      }
    }
    runs.sort((x, y) => y.at - x.at);
    return {
      attempts: list.slice(0, 30).map((a) => ({ id: a.id, sport: a.sport, createdAt: a.createdAt, picks: a.picks.length, complete: complete(a), locked: a.locked, runCount: a.runs.length })),
      runs: runs.slice(0, 40), best,
      totals: { attempts: list.length, runs: runs.length, perfect: runs.filter((r) => r.success).length },
    };
  }

  return { config, start, roll: start, open, pick, nextRoll, reroll, lock, rebuild, unlock: rebuild, simulate, runView, view, mine };
}

