// Games: the challenge lifecycle.
//   roll      -> random sport season + random team that played it (server-side,
//                so nobody can pick their roll) -> a new attempt
//   squad     -> save a draft (checked on every save)
//   lock      -> a complete, legal squad is locked for simulation
//   simulate  -> a seeded season; the run's summary is stored
//   unlock    -> "rebuild": same team-season, change the squad, sim again
// A run stores its squad and seed, so its full season can be replayed exactly
// (GET .../runs/:n) instead of storing every game.

const crypto = require('node:crypto');
const { SPORTS, ORDER, seasonsFor, publicSport } = require('./sports');
const squadLib = require('./squad');
const sim = require('./sim');
const fantasy = require('./fantasy');
const chemistry = require('./chemistry');

class GameError extends Error { constructor(code, msg) { super(msg); this.code = code; } }

const ENGINE = 2; // bump when the sim changes in a way that alters replays (2: fantasy PPG + chemistry model)
const MAX_TRIES = 6;
const DISCLAIMER = 'Simulated seasons are generated by the GMmode simulator. They are not real games and never happened. Rosters, player stats and fantasy points are real, from that season\'s ESPN box scores; chemistry links come from ESPN athlete records.';

function createService({ store, history, random = Math.random, now = Date.now }) {
  const db = store.db;
  db.attempts ||= {};

  const get = (id) => {
    const a = db.attempts[String(id || '')];
    if (!a) throw new GameError(404, 'That challenge doesn\'t exist (or it was cleared).');
    return a;
  };
  const own = (uid, id) => {
    const a = get(id);
    if (a.uid !== uid) throw new GameError(403, 'That\'s someone else\'s challenge. Start your own!');
    return a;
  };
  const sportOf = (key) => { if (!SPORTS[key]) throw new GameError(400, 'Pick a sport.'); return key; };

  function config() {
    return {
      sports: ORDER.map(publicSport), disclaimer: DISCLAIMER,
      scoring: Object.fromEntries(ORDER.map((k) => [k, fantasy.describe(k)])), chemistry: chemistry.describe(),
    };
  }

  // A random team-season with enough real data to draft a full squad.
  async function roll(uid, sportKey) {
    sportOf(sportKey);
    const seasons = seasonsFor(sportKey);
    let lastErr = null;
    for (let i = 0; i < MAX_TRIES; i++) {
      const season = seasons[Math.floor(random() * seasons.length)];
      try {
        const st = await history.standings(sportKey, season);
        const team = st.teams[Math.floor(random() * st.teams.length)];
        const ts = await history.teamSeason(sportKey, season, team.id);
        if (ts.partial) { lastErr = new Error('ESPN fetches failed mid-season'); continue; }
        if (ts.coverage.boxScores < ts.coverage.games * 0.8) { lastErr = new Error('thin box scores'); continue; }
        const full = squadLib.check(sportKey, ts.players, squadLib.best(sportKey, ts.players));
        if (full.missing.length) { lastErr = new Error('roster can\'t fill every slot'); continue; }
        const id = crypto.randomUUID();
        db.attempts[id] = {
          id, uid, sport: sportKey, season, teamId: ts.team.id, team: { name: ts.team.name, abbr: ts.team.abbr, logo: ts.team.logo },
          seasonLabel: ts.seasonLabel, createdAt: now(), squad: {}, locked: false, runs: [],
        };
        store.save();
        return view(uid, id);
      } catch (e) { lastErr = e; }
    }
    console.error(`[games] roll ${sportKey} failed: ${lastErr?.message}`);
    throw new GameError(503, 'Couldn\'t pull a historical roster right now. ESPN may be slow, so give it another try.');
  }

  // Never draft or simulate from a season with gaps caused by failed fetches.
  async function teamSeasonOf(a) {
    const busy = () => new GameError(503, `Couldn't load the full ${a.seasonLabel} ${a.team.name} roster from ESPN right now. Try again in a minute.`);
    let ts;
    try { ts = await history.teamSeason(a.sport, a.season, a.teamId); } catch { throw busy(); }
    if (ts.partial) throw busy();
    return ts;
  }

  function publicTeamSeason(ts) {
    return {
      season: ts.season, seasonLabel: ts.seasonLabel, team: ts.team, record: ts.record, coverage: ts.coverage, source: ts.source,
      games: ts.schedule.length,
      schedule: ts.schedule.map((g, i) => ({ n: i + 1, date: g.date, home: g.home, opp: g.opp, real: g.real })),
      history: ts.coverage.history || null,
      players: ts.players.map((p) => ({
        id: p.id, name: p.name, pos: p.pos, elig: p.elig, group: p.group, gp: p.gp, key: p.key, line: p.line, pkey: p.pkey || null, pline: p.pline || null,
        ppg: p.ppg, mppg: p.mppg, pg: p.pg,
        fp: Object.fromEntries(Object.entries(p.fp).map(([g, x]) => [g, { gp: x.gp, ppg: x.ppg, mppg: x.mppg, parts: x.parts.map((y) => ({ label: y.label, n: Math.round(y.n * 10) / 10, ppg: y.ppg })) }])),
        college: ts.bios?.[p.id]?.college || null, historyKnown: !!ts.bios?.[p.id]?.known,
      })),
    };
  }

  function publicAttempt(a, uid) {
    return {
      id: a.id, sport: a.sport, season: a.season, seasonLabel: a.seasonLabel, team: a.team, createdAt: a.createdAt,
      squad: a.squad, locked: a.locked, mine: a.uid === uid, runs: a.runs.map(({ squad, seed, ...r }) => r),
    };
  }

  // Combined fantasy PPG and chemistry for whatever's drafted so far, which
  // undrafted players would add chemistry, and (once complete) a projection.
  // The percentile and win-model constants stay server-side.
  function preview(a, ts, squad) {
    const res = squadLib.resolve(a.sport, ts.players, squad);
    const prof = sim.profile(a.sport, ts, res);
    const members = res.filter((s) => s.player).map((s) => ({ id: s.player.id, name: s.player.name, ppg: s.ppg || 0 }));
    const inSquad = new Set(members.map((m) => m.id));
    const hints = {};
    if (members.length) {
      for (const p of ts.players) {
        if (inSquad.has(p.id)) continue;
        const d = chemistry.delta(members, { id: p.id, name: p.name, ppg: p.mppg }, ts.pairs || {});
        if (d.with.length) hints[p.id] = d;
      }
    }
    const out = {
      complete: prof.complete, combined: prof.combined, base: prof.base,
      chem: { total: prof.chem.total, players: Object.fromEntries(Object.entries(prof.chem.players).map(([id, x]) => [id, { bonus: x.bonus, links: x.links, capped: !!x.capped }])), links: prof.chem.links.map((l) => ({ a: l.a, b: l.b, aName: l.aName, bName: l.bName, ppg: l.ppg, kinds: l.kinds })) },
      slots: prof.slots, hints, odds: null,
    };
    if (prof.complete) {
      const seed = `${a.id}:preview:${JSON.stringify(squad)}`;
      const o = sim.odds({ sportKey: a.sport, ts, res, runs: 300, seed });
      out.odds = { chance: o.chance, avgWins: o.avgWins, low: o.low, high: o.high, games: o.games, runs: o.runs, objective: o.objective };
      if (prof.chem.total > 0) {
        const w = sim.odds({ sportKey: a.sport, ts, res, runs: 300, seed, chem: false });
        out.odds.chemWins = Math.round((o.avgWins - w.avgWins) * 10) / 10;
      }
    }
    return out;
  }

  async function view(uid, id, { run = null } = {}) {
    const a = get(id);
    const ts = await teamSeasonOf(a);
    const out = { attempt: publicAttempt(a, uid), rules: publicSport(a.sport), teamSeason: publicTeamSeason(ts), disclaimer: DISCLAIMER };
    out.preview = preview(a, ts, a.squad);
    const n = run ?? a.runs.length;
    if (n) out.result = await replay(a, ts, n);
    return out;
  }

  async function saveSquad(uid, id, squad) {
    const a = own(uid, id);
    if (a.locked) throw new GameError(409, 'This squad is locked in. Hit "Rebuild squad" to make changes.');
    const ts = await teamSeasonOf(a);
    const c = squadLib.check(a.sport, ts.players, squad);
    if (c.errors.length) throw new GameError(400, c.errors[0]);
    a.squad = c.squad;
    store.save();
    return { squad: a.squad, missing: c.missing, preview: preview(a, ts, a.squad) };
  }

  async function lock(uid, id, squad) {
    const a = own(uid, id);
    if (a.locked) return view(uid, id);
    const ts = await teamSeasonOf(a);
    const c = squadLib.check(a.sport, ts.players, squad ?? a.squad, { complete: true });
    if (c.errors.length) throw new GameError(400, c.errors[0]);
    a.squad = c.squad; a.locked = true;
    store.save();
    return view(uid, id);
  }

  function unlock(uid, id) {
    const a = own(uid, id);
    a.locked = false;
    store.save();
    return { ok: true };
  }

  async function simulate(uid, id) {
    const a = own(uid, id);
    if (!a.locked) throw new GameError(409, 'Lock in your squad first.');
    if (a.runs.length >= 50) throw new GameError(429, 'That\'s 50 sims of this squad. Roll a new team!');
    const ts = await teamSeasonOf(a);
    const n = a.runs.length + 1, seed = `${a.id}:${n}`;
    const odds = preview(a, ts, a.squad).odds;
    const res = squadLib.resolve(a.sport, ts.players, a.squad);
    const r = sim.simulateSeason({ sportKey: a.sport, ts, res, seed });
    a.runs.push({
      n, seed, engine: ENGINE, at: now(), squad: { ...a.squad },
      record: r.record, played: r.played, success: r.success, perfect: r.perfect, undefeated: r.undefeated,
      combined: r.team.combined, chem: r.team.chem, maxStreak: r.maxStreak, firstBlemish: r.firstBlemish, pf: r.pf, pa: r.pa, tier: r.tier, beatReal: r.beatReal,
      mvp: r.mvp ? { name: r.mvp.name, slot: r.mvp.slotLabel, line: r.mvp.sim } : null, chance: odds?.chance ?? null, chemWins: odds?.chemWins ?? null,
    });
    store.save();
    return view(uid, id, { run: n });
  }

  async function replay(a, ts, n) {
    const run = a.runs[n - 1];
    if (!run) throw new GameError(404, 'No such run.');
    const res = squadLib.resolve(a.sport, ts.players, run.squad);
    const r = sim.simulateSeason({ sportKey: a.sport, ts, res, seed: run.seed });
    // If the engine changed since this run, the stored summary is what happened.
    const drift = r.record.w !== run.record.w || r.record.l !== run.record.l || r.record.t !== run.record.t || r.record.otl !== run.record.otl;
    return { n, of: a.runs.length, at: run.at, chance: run.chance, chemWins: run.chemWins ?? null, drift, engine: run.engine, ...r };
  }

  async function runView(uid, id, n) {
    return view(uid, id, { run: Number(n) });
  }

  // Your attempts, newest first, and your best run per sport.
  function mine(uid) {
    const list = Object.values(db.attempts).filter((a) => a.uid === uid).sort((x, y) => y.createdAt - x.createdAt);
    const score = (r) => (r.success ? 1e6 : 0) + (r.record.w + 0.5 * r.record.t) / r.played * 1e3 + r.maxStreak;
    const best = {};
    const runs = [];
    for (const a of list) {
      for (const r of a.runs) {
        const row = { attemptId: a.id, sport: a.sport, seasonLabel: a.seasonLabel, team: a.team, n: r.n, at: r.at, record: r.record, played: r.played, success: r.success, perfect: r.perfect, combined: r.combined ?? null, chem: r.chem ?? null, maxStreak: r.maxStreak, tier: r.tier, mvp: r.mvp, chance: r.chance, pf: r.pf, pa: r.pa, beatReal: r.beatReal };
        runs.push(row);
        if (!best[a.sport] || score(r) > score(best[a.sport])) best[a.sport] = row;
      }
    }
    runs.sort((x, y) => y.at - x.at);
    return {
      attempts: list.slice(0, 30).map((a) => ({ ...publicAttempt(a, uid), runs: undefined, runCount: a.runs.length, last: a.runs.length ? (({ squad, seed, ...r }) => r)(a.runs[a.runs.length - 1]) : null })),
      runs: runs.slice(0, 40), best,
      totals: { attempts: list.length, runs: runs.length, perfect: runs.filter((r) => r.success).length },
    };
  }

  return { config, roll, view, saveSquad, lock, unlock, simulate, runView, mine };
}

module.exports = { createService, GameError, DISCLAIMER, ENGINE };
